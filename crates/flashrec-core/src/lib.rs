//! flashrec — відновлення файлів із флешок, що відмовляють.
//!
//! Рушій розбито так, щоб кожен етап можна було взяти окремо:
//!
//! - [`device`] знаходить фізичні диски й відкриває їх на сире читання;
//! - [`imaging`] копіює диск в образ і записує кожен нечитаний сектор;
//! - [`ntfs`], [`fat`] і [`exfat`] розбирають свої файлові системи;
//! - [`files`] — спільне для всіх: перелік файлів, шляхи, запис на диск;
//! - `cluster` (внутрішній) — таблиця FAT і ланцюжки кластерів, спільні для FAT і exFAT;
//! - [`carve`] знаходить вміст файлів за сигнатурами, коли метаданих не лишилось;
//! - [`partition`] знаходить том усередині образу цілого диска;
//! - [`source`] відкриває образ або живий диск однаково для CLI і GUI;
//! - [`reader`] — побайтовий шар, через який читає все вище.
//!
//! Ніщо тут ніколи не пише на диск, який відновлюється.

pub mod carve;
pub(crate) mod cluster;
pub mod device;
pub mod exfat;
pub mod fat;
pub mod files;
pub mod imaging;
pub mod ntfs;
pub mod partition;
pub mod reader;
pub mod source;

#[cfg(windows)]
pub mod sys;

